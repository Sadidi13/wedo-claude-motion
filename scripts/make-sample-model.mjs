#!/usr/bin/env node
/**
 * Builds the glTF model of the "3D product" sample in code (no third-party model
 * file, so no licence question) and writes it as a data URL module:
 *
 *   node scripts/make-sample-model.mjs   ->   src/samples/productModel.ts
 *
 * A serum bottle: lathed glass-coloured body, white label band and a gold cap,
 * about 1.7 units tall, standing on y = 0. UVs are dropped to keep it small.
 */
import { writeFile } from "node:fs/promises";
import path from "node:path";
import { fileURLToPath } from "node:url";
import * as THREE from "three";
import { GLTFExporter } from "three/addons/exporters/GLTFExporter.js";

// GLTFExporter reads its Blob output with FileReader, which Node does not have.
globalThis.FileReader ??= class {
  readAsArrayBuffer(blob) {
    void blob.arrayBuffer().then((buffer) => {
      this.result = buffer;
      this.onloadend?.();
    });
  }
  readAsDataURL(blob) {
    void blob.arrayBuffer().then((buffer) => {
      this.result = `data:${blob.type};base64,${Buffer.from(buffer).toString("base64")}`;
      this.onloadend?.();
    });
  }
};

const SEGMENTS = 40;

function lathe(points, material, name) {
  const geometry = new THREE.LatheGeometry(points.map(([x, y]) => new THREE.Vector2(x, y)), SEGMENTS);
  geometry.deleteAttribute("uv");
  const mesh = new THREE.Mesh(geometry, material);
  mesh.name = name;
  return mesh;
}

const bottle = new THREE.Group();
bottle.name = "Bottle";
bottle.add(
  lathe(
    [[0, 0], [0.4, 0], [0.47, 0.04], [0.5, 0.14], [0.5, 1.02], [0.46, 1.12], [0.3, 1.2], [0.16, 1.24], [0.16, 1.32], [0, 1.32]],
    new THREE.MeshStandardMaterial({ name: "Glass", color: "#1f6f78", roughness: 0.18, metalness: 0.1 }),
    "Body",
  ),
  lathe(
    [[0.505, 0.38], [0.505, 0.78]],
    new THREE.MeshStandardMaterial({ name: "Label", color: "#f4f1ea", roughness: 0.6, metalness: 0, side: THREE.DoubleSide }),
    "Label",
  ),
  lathe(
    [[0, 1.3], [0.2, 1.3], [0.22, 1.33], [0.22, 1.66], [0.2, 1.7], [0, 1.7]],
    new THREE.MeshStandardMaterial({ name: "Gold", color: "#d9b25f", roughness: 0.28, metalness: 1 }),
    "Cap",
  ),
);

const glb = await new GLTFExporter().parseAsync(bottle, { binary: true });
const dataUrl = `data:model/gltf-binary;base64,${Buffer.from(glb).toString("base64")}`;
const out = path.join(path.dirname(fileURLToPath(import.meta.url)), "..", "src", "samples", "productModel.ts");
await writeFile(
  out,
  `/**\n * Generated by scripts/make-sample-model.mjs (do not edit): the serum bottle of the\n * "3D product" sample as a GLB data URL, ${glb.byteLength} bytes.\n */\nexport const PRODUCT_MODEL_GLB =\n  "${dataUrl}";\n`,
);
console.log(`wrote ${path.relative(process.cwd(), out)} (${glb.byteLength} bytes GLB)`);
