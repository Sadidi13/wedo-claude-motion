/**
 * The media library (docs/VIDEO.md): footage, sound, images and fonts too large to live in a
 * project as data: URLs are imported once into the local server's library and referenced from
 * scene code as `media/<id>.<ext>`, e.g. `<Video src="media/k3f9x2abcd12.mp4" />`,
 * `<Audio src="media/p0q1r2s3t4u5.mp3" />`, `<img src="media/a1b2c3d4e5f6.png" />` or
 * `url("media/z9y8x7w6v5u4.ttf")` in CSS. This module is shared by the runtime, the editor and the
 * server: the reference format, the metadata the server keeps per file, the URLs it serves and the
 * frame a stage time maps to.
 */

/** 12 lowercase letters / digits, generated by the server on import. */
export const MEDIA_ID_PATTERN = /^[a-z0-9]{12}$/;

const MEDIA_REF = /^(?:\.?\/)?media\/([a-z0-9]{12})(?:\.[a-z0-9]{1,8})?$/;
const MEDIA_REFS_IN_TEXT = /\bmedia\/([a-z0-9]{12})\b/g;

/** The media id of a `media/<id>[.ext]` reference, or null for anything else. */
export function mediaIdOf(src: string | null | undefined): string | null {
  if (typeof src !== "string") return null;
  return MEDIA_REF.exec(src.trim())?.[1] ?? null;
}

/** Every media id a piece of scene code mentions, once each, in order of appearance. */
export function mediaIdsIn(text: string): string[] {
  return [...new Set([...text.matchAll(MEDIA_REFS_IN_TEXT)].map((m) => m[1]))];
}

export function mediaRef(id: string, ext: string): string {
  return ext ? `media/${id}.${ext}` : `media/${id}`;
}

export type MediaState = "processing" | "ready" | "error";

/** What a library file is; decided by its extension on import. */
export type MediaKind = "video" | "audio" | "image" | "font";

/** Whisper's transcript of a video's or a sound's speech (made on request: POST /api/media/<id>/transcript). */
export interface TranscriptStatus {
  state: "processing" | "ready" | "error";
  error?: string;
  /** language Whisper heard (or was told), e.g. "fa" */
  language?: string;
  /** the designer corrected the text */
  edited?: boolean;
}

/** What the server knows about one imported file (`GET /api/media/<id>`). */
export interface MediaMeta {
  id: string;
  /** absent on files imported before the library took more than video */
  kind?: MediaKind;
  /** the file name it was imported under */
  name: string;
  /** lowercase extension of the source file, without the dot */
  ext: string;
  /** source size in bytes */
  size: number;
  state: MediaState;
  error?: string;
  /** seconds (0 until known) */
  duration: number;
  /** frame rate of the source, when ffmpeg reports one */
  sourceFps: number;
  /** pixel size of the source as displayed (rotation applied); 0 until known */
  width: number;
  height: number;
  hasAudio: boolean;
  /** export frames: one JPEG every 1/frameRate s, `frameCount` of them, `frameWidth` × `frameHeight` */
  frameRate: number;
  frameCount: number;
  frameWidth: number;
  frameHeight: number;
  /** fonts: the family, weight and style the file's name table declares */
  fontFamily?: string;
  fontWeight?: number;
  fontStyle?: "normal" | "italic";
  transcript?: TranscriptStatus;
  createdAt: string;
}

export function mediaKindOf(meta: Pick<MediaMeta, "kind">): MediaKind {
  return meta.kind ?? "video";
}

export const mediaUrls = {
  meta: (id: string) => `/api/media/${id}`,
  /** a light H.264 copy for smooth playback in the editor */
  preview: (id: string) => `/api/media/${id}/preview`,
  /** frame `n` (0-based) as JPEG, used by exports */
  frame: (id: string, n: number) => `/api/media/${id}/frames/${n}`,
  /** the file as imported (sound, images and fonts load it directly) */
  file: (id: string) => `/api/media/${id}/file`,
  transcript: (id: string) => `/api/media/${id}/transcript`,
};

/** The export frame that shows source time `seconds` (clamped to the frames that exist). */
export function frameAt(meta: Pick<MediaMeta, "frameRate" | "frameCount">, seconds: number): number {
  if (meta.frameCount <= 0) return 0;
  const index = Math.floor(Math.max(0, seconds) * meta.frameRate + 1e-4);
  return Math.min(meta.frameCount - 1, index);
}

/** Extensions the library accepts, per kind (the browser plays a video's preview copy, ffmpeg reads the rest). */
export const VIDEO_EXTENSIONS = ["mp4", "mov", "m4v", "webm", "mkv", "avi"] as const;
export const AUDIO_EXTENSIONS = ["mp3", "wav", "m4a", "aac", "ogg", "oga", "opus", "flac"] as const;
export const IMAGE_EXTENSIONS = ["png", "jpg", "jpeg", "webp", "gif", "avif", "svg"] as const;
export const FONT_EXTENSIONS = ["ttf", "otf", "woff", "woff2"] as const;

const KIND_BY_EXTENSION = new Map<string, MediaKind>([
  ...VIDEO_EXTENSIONS.map((ext) => [ext, "video"] as const),
  ...AUDIO_EXTENSIONS.map((ext) => [ext, "audio"] as const),
  ...IMAGE_EXTENSIONS.map((ext) => [ext, "image"] as const),
  ...FONT_EXTENSIONS.map((ext) => [ext, "font"] as const),
]);

