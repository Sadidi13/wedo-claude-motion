/** The kind a file name's extension makes it, or null when the library does not take it. */
export function mediaKindForName(name: string): MediaKind | null {
  const ext = name.toLowerCase().split(".").pop() ?? "";
  return KIND_BY_EXTENSION.get(ext) ?? null;
}

export function isVideoFileName(name: string): boolean {
  return mediaKindForName(name) === "video";
}

/** Extensions loaded by URL in scene code (`<img src>`, CSS `url()`), which the loader points at /api/media/<id>/file. */
export const URL_LOADED_EXTENSIONS: readonly string[] = [...IMAGE_EXTENSIONS, ...FONT_EXTENSIONS];
